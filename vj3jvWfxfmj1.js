function temporarilyHideRandomButtons(rowIndex, count = 1, duration = 2000) {
    // Pick 'count' unique random indices in the row
    const indices = [];
    while (indices.length < count) {
        const rand = Math.floor(Math.random() * 9);
        if (!indices.includes(rand)) {
            indices.push(rand);
        }
    }
    // Hide selected buttons
    indices.forEach(j => {
        const btn = document.getElementById(`z[${rowIndex}][${j}]`);
        if (btn) btn.style.opacity = "0";
    });
    // Restore after 'duration' ms
    setTimeout(() => {
        indices.forEach(j => {
            const btn = document.getElementById(`z[${rowIndex}][${j}]`);
            if (btn) btn.style.opacity = "1";
        });
    }, duration);
}
